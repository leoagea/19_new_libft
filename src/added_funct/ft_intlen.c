#include "../../libft.h"

size_t    ft_intlen(int n)
{
    size_t	len;

    len = 0;
    if (n < 0)
    {
        n = -n;
        len++;
    }
    if (n == 0)
        return (1);
    while (n > 0)
    {
        n /= 10;
        len++;
    }
    return (len);
}
